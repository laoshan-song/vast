  function rewriteLinks() {
    document.querySelectorAll("a[href], link[href]").forEach((a) => {
      const raw = a.getAttribute("href");
      if (!raw || /^(https?:|mailto:|#)/i.test(raw)) return;
      const replaced = raw.replace(/(^|\/)(overview|q1|q2|q3)\.html(?=([?#]|$))/i, (m, slash, name) => {
        return `${slash}${pageLinks[`${name.toLowerCase()}.html`]}`;
      });
      if (replaced !== raw) a.setAttribute("href", replaced);
    });
    document.querySelectorAll("[data-page]").forEach((el) => {
      const raw = el.getAttribute("data-page");
      if (pageLinks[raw]) el.setAttribute("data-page", pageLinks[raw]);
    });
  }

  function shouldSkip(node) {
    const el = node.nodeType === Node.TEXT_NODE ? node.parentElement : node;
    return !el || Boolean(el.closest("script,style,code,pre,textarea"));
  }

  function preserveTranslate(value) {
    if (!value || !value.trim()) return value;
    const lead = value.match(/^\s*/)[0];
    const trail = value.match(/\s*$/)[0];
    let core = value.trim();
    if (exact.has(core)) return `${lead}${exact.get(core)}${trail}`;
    for (const [re, zh] of replacements) core = core.replace(re, zh);
    core = core
      .replace(/\bstep\s+(\d+)/gi, "步骤 $1")
      .replace(/\bhop\s+(\d+)/gi, "跳数 $1")
      .replace(/\bid\s+(\d+)/gi, "ID $1")
      .replace(/\b(\d+)\s+relay hops\b/gi, "$1 个转发跳数")
      .replace(/\b(\d+)\s+delete events\b/gi, "$1 个删除事件")
      .replace(/\b(\d+)\s+SaidIt posts\b/gi, "$1 条 SaidIt 帖子")
      .replace(/\bunknown \/ outside data window\b/gi, "未知 / 在数据窗口之外")
      .replace(/\bnot observed\b/gi, "未观测到")
      .replace(/\bnot available\b/gi, "不可得");
    return `${lead}${core}${trail}`;
  }

  function translateNodeText(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return shouldSkip(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const next = preserveTranslate(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    });
  }

  function translateAttrs(root) {
    root.querySelectorAll?.("[aria-label], [title], [alt]").forEach((el) => {
      ["aria-label", "title", "alt"].forEach((attr) => {
        const value = el.getAttribute(attr);
        if (!value) return;
        const next = preserveTranslate(value);
        if (next !== value) el.setAttribute(attr, next);
      });
    });
  }

  let pending = false;
  function translateAll() {
    pending = false;
    document.title = preserveTranslate(document.title);
    rewriteLinks();
    applyStaticOverrides();
    translateNodeText(document.body);
    translateAttrs(document.body);
  }

  function scheduleTranslate() {
    if (pending) return;
    pending = true;
    setTimeout(translateAll, 0);
  }

  document.addEventListener("DOMContentLoaded", () => {
    scheduleTranslate();
    setTimeout(scheduleTranslate, 120);
    setTimeout(scheduleTranslate, 600);
    const mo = new MutationObserver(scheduleTranslate);
    mo.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "alt", "href"] });
  });
